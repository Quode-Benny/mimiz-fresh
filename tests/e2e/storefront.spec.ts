import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
test('Ghanaian menu, meal options and saved bag', async ({page}, info) => {
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'A little taste of home.'})).toBeVisible();
 await page.getByRole('button',{name:'All items',exact:true}).click();
 await expect(page.locator('.dish')).toHaveCount(14);
 await expect(page.locator('.dish')).toHaveCount(14);
 await page.getByRole('button',{name:'Breakfast',exact:true}).click();
 await expect(page.locator('.dish')).toHaveCount(1);
 await page.getByRole('button',{name:'Everything',exact:true}).click();
 await page.getByRole('searchbox',{name:'Search the menu'}).fill('not-on-the-menu');
 await expect(page.getByRole('heading',{name:'No dishes match just yet.'})).toBeVisible();
 await page.getByRole('button',{name:'Show the whole menu'}).click();
 await page.getByRole('button',{name:'Vegetarian',exact:true}).click();
 await expect(page.getByTestId('dish-red-red')).toBeVisible();
 await expect(page.getByTestId('dish-banku')).toHaveCount(0);
 await page.getByRole('button',{name:'Vegetarian',exact:true}).click();
 await page.getByRole('button',{name:'Add Smoky Ghana jollof to bag',exact:true}).click();
 const meal=page.getByRole('dialog');
 await meal.getByRole('radio',{name:'Fried fish'}).check();
 await meal.getByRole('checkbox',{name:'Boiled egg'}).check();
 await meal.getByRole('textbox',{name:'A note for the kitchen'}).fill('Less pepper, please.');
 await meal.getByRole('button',{name:'Increase quantity'}).click();
 await expect(meal.getByRole('button',{name:/Add to bag/})).toContainText('160.00');
 await meal.getByRole('button',{name:/Add to bag/}).click();
 await page.locator('header').getByRole('button',{name:'Open bag, 2 items'}).click();
 const bag=page.getByRole('dialog');
 await expect(bag.getByTestId('basket-total')).toHaveText('\u20b5160.00');
 await expect(bag.getByText('Note: Less pepper, please.')).toBeVisible();
 await bag.getByRole('button',{name:'Remove one Smoky Ghana jollof'}).click();
 await expect(bag.getByTestId('basket-total')).toHaveText('\u20b580.00');
 await page.keyboard.press('Escape');await page.reload();
 await page.locator('header').getByRole('button',{name:'Open bag, 1 items'}).click();
 await expect(page.getByTestId('basket-total')).toHaveText('\u20b580.00');
 await mkdir('artifacts/screenshots',{recursive:true});
 await page.screenshot({path:'artifacts/screenshots/'+info.project.name+'-basket.png'});
 await page.keyboard.press('Escape');
 await page.locator('img').evaluateAll(images=>Promise.all(images.map(image=>image.decode().catch(()=>{}))));
 expect(await page.locator('img').evaluateAll(images=>images.filter(image=>!image.complete||!image.naturalWidth).length)).toBe(0);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.evaluate(()=>window.scrollTo({top:0,behavior:"instant"}));
 await page.screenshot({path:'artifacts/screenshots/'+info.project.name+'-storefront.png',fullPage:true});
 expect(errors).toEqual([]);
});

