test('corrupt storage recovery',async({page})=>{
 await page.addInitScript(()=>localStorage.setItem('mimiz-fresh-basket-v2','not valid JSON'));
 await page.goto('/');
 await expect(page.getByText('Your saved preview bag could not be imported. Your server bag is still available.')).toBeVisible();
 await page.locator('header').getByRole('button',{name:'Open bag, 0 items'}).click();
 await expect(page.getByRole('heading',{name:'Something delicious belongs here.'})).toBeVisible();
});
